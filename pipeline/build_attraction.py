def classify(cat):
    if cat is None or (isinstance(cat, float) and pd.isna(cat)) or cat == '':
        return ('other','uncategorised',0)
    return EXACT.get(cat, ('other','unmapped',0))

# ---------------------------------------------------------------- load places
gj = json.load(open(PLACES))
rows = []
for f in gj['features']:
    p = f['properties']; x, y = f['geometry']['coordinates']
    cats = [p.get(f'categories/{i}') for i in range(35)]
    cats = [c for c in cats if c not in (None, '')]
    rows.append(dict(placeId=p['placeId'], name=p.get('name'), brand=p.get('brandName'),
                     address=p.get('addressFull'), cat0=cats[0] if cats else p.get('categoryPrimary'),
                     all_cats=' | '.join(cats), n_cats=len(cats),
                     rating=p.get('rating'), reviews=p.get('reviewCount'),
                     gis_districtId=p.get('districtId'), lon=x, lat=y,
                     _cats=cats))
df = pd.DataFrame(rows)

# ---------------------------------------------------------------- purpose assignment
# primary category first; if it carries no weight, take the highest-weight mapped category among the rest
purp, sub, w, src = [], [], [], []
for cats, c0 in zip(df._cats, df.cat0):
    pu, su, we = classify(c0); how = 'primary'
    if we == 0 and len(cats) > 1:
        best = max((classify(c) for c in cats[1:]), key=lambda t: t[2])
        if best[2] > 0:
            pu, su, we = best; how = 'secondary_category'
    purp.append(pu); sub.append(su); w.append(we); src.append(how)
df['purpose'], df['subtype'], df['weight'], df['assigned_from'] = purp, sub, w, src
df = df.drop(columns='_cats')

# ---------------------------------------------------------------- districts (point in polygon)
dj = json.load(open(DISTRICTS))
polys = [(f['properties']['d_id'], shape(f['geometry'])) for f in dj['features']]
tree = STRtree([g for _, g in polys])
ids = [i for i, _ in polys]
dist = []
for x, y in zip(df.lon, df.lat):
    hit = tree.query(Point(x, y), predicate='within')
    dist.append(ids[hit[0]] if len(hit) else None)
df['d_id'] = dist
outside = df.d_id.isna().sum()

# ---------------------------------------------------------------- aggregate
inside = df[df.d_id.notna()].copy()
inside['d_id'] = inside.d_id.astype(int)
active = inside[inside.weight > 0]
cnt = active.pivot_table(index='d_id', columns='purpose', values='placeId', aggfunc='count', fill_value=0)
wt  = active.pivot_table(index='d_id', columns='purpose', values='weight',  aggfunc='sum',   fill_value=0)
cnt.columns = [f'{c}_count' for c in cnt.columns]
wt.columns  = [f'{c}_weighted' for c in wt.columns]
share = wt.div(wt.sum(axis=0), axis=1); share.columns = [c.replace('_weighted', '_share') for c in share.columns]
rawshare = cnt.div(cnt.sum(axis=0), axis=1); rawshare.columns = [c.replace('_count', '_rawcount_share') for c in rawshare.columns]
table = pd.concat([cnt, wt.round(1), share.round(4), rawshare.round(4)], axis=1).reset_index()
table.to_csv(f'{OUT}/district_attraction.csv', index=False)

# per-district subtype breakdown (for auditing)
sub_tab = active.pivot_table(index='d_id', columns=['purpose','subtype'], values='weight', aggfunc='sum', fill_value=0).round(1)
sub_tab.columns = [f'{a}:{b}' for a, b in sub_tab.columns]
sub_tab.reset_index().to_csv(f'{OUT}/district_attraction_by_subtype.csv', index=False)

# editable category map + slim place file
cm = (df.assign(c=df.cat0.fillna('<none>')).groupby('c')
        .agg(n_places=('placeId','count'), purpose=('purpose','first'), subtype=('subtype','first'), weight=('weight','first'))
        .reset_index().rename(columns={'c':'category'}).sort_values('n_places', ascending=False))
cm.to_csv(f'{OUT}/category_mapping.csv', index=False)
df.drop(columns=['all_cats']).to_csv(f'{OUT}/places_assigned.csv', index=False)

